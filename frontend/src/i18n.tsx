export type MsgKey = keyof typeof zh;


// English is loaded on demand (src/i18n.en.ts) so the default bundle only
// carries the Chinese dictionary; until it arrives, t() falls back to zh.
let enCache: Record<MsgKey, string> | null = null;
function loadEn(): Promise<Record<MsgKey, string>> {
  if (enCache) return Promise.resolve(enCache);
  return import("./i18n.en").then((m) => (enCache = m.en));
}

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MsgKey, vars?: Record<string, string | number>) => string;
}

const LangContext = createContext<I18n>({
  lang: "zh",
  setLang: () => {},
  t: (key) => zh[key],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const [en, setEn] = useState<Record<MsgKey, string> | null>(enCache);

  useEffect(() => {
    if (lang === "en" && !en) void loadEn().then(setEn);
  }, [lang, en]);

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const t = useCallback(
    (key: MsgKey, vars?: Record<string, string | number>) => {
      let text: string = (lang === "en" && en ? en[key] : undefined) ?? zh[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(value));
        }
      }
      return text;
    },
    [lang, en],
  );

  return <LangContext.Provider value={{ lang, setLang: setLangState, t }}>{children}</LangContext.Provider>;
}

export function useT(): I18n {
  return useContext(LangContext);
}
